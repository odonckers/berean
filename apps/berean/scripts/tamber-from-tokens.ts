// Writes apps/berean/app.tamber, and the theme and accent names in app.contract's
// tokens block, from docs/design/themes/tokens.json, the one source of Berean's
// colours (themes-spec.md §12.1), so the Exact app hand-copies no hex or name.
// Run it in apps/berean after any change to tokens.json:
//
//   bun scripts/tamber-from-tokens.ts           writes both
//   bun scripts/tamber-from-tokens.ts --check   fails if either has drifted (CI)
//
// The design has two axes the person picks on Settings › Appearance: `theme`
// (paper, sepia, stone, sage) and `accent` (slot one to six). Light and dark
// are each token's `light-dark()`. Exact can't yet vary a token by the system's
// Increase Contrast setting (a host trait, LLP 1121 D5), so the IC sets in
// tokens.json wait for it. A platform role can't vary by an app axis either,
// so the app tint is `accent-color="accent"` on app.contract's root, and the
// page is `page`, not `background`.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = join(here, '../../../docs/design/themes/tokens.json');
const OUT = join(here, '../app.tamber');
const CONTRACT = join(here, '../app.contract');
const BEGIN = '// tokens:begin (scripts/tamber-from-tokens.ts writes this block from tokens.json)';
const END = '// tokens:end';

type Mode = { [role: string]: unknown; highlights: { key: string; hex: string }[] };
type Slot = { slot: number; name: string; modes: Record<string, { hex: string; onAccent: string }> };
type Theme = { name: string; modes: Record<string, Mode>; accents: { slots: Slot[] } };
type Tokens = {
  defaults: { theme: string; accentSlot: number };
  roles: string[];
  highlightFamilies: { order: number; key: string }[];
  themes: Record<string, Theme>;
};

/** The accent axis's values, slot 1 first. */
export const SLOTS = ['one', 'two', 'three', 'four', 'five', 'six'];

/** Roles that follow the accent the person picks, not slot 1 (spec §3 rule 9). */
const ACCENT_ROLES = new Set(['accent', 'onAccent', 'focusRing']);

/** Token names where a role's own would override a platform role (`background`, `separator`). */
const RENAMED: Record<string, string> = {
  background: 'page',
  outline: 'line.outline',
  separator: 'line.separator',
  linkUnderline: 'line.link',
};

/** `textPrimary` → `text.primary`, `onAccent` → `on.accent`. */
export function tokenName(role: string): string {
  return RENAMED[role] ?? role.replace(/([a-z])([A-Z])/g, '$1.$2').toLowerCase();
}

function hex(value: unknown, at: string): string {
  if (typeof value !== 'string' || !/^#[0-9A-F]{6}$/.test(value)) throw new Error(`${at}: not an opaque #RRGGBB`);
  return value.toLowerCase();
}

const pair = (light: string, dark: string) => `light-dark(${light}, ${dark})`;

export function render(tokens: Tokens): string {
  const ids = Object.keys(tokens.themes);
  const first = tokens.defaults.theme;
  if (ids[0] !== first) throw new Error(`the default theme ${first} must come first in tokens.json`);
  if (tokens.defaults.accentSlot !== 1) throw new Error('the default accent must be slot 1');
  const others = ids.slice(1);
  const lines: string[] = [];
  const out = (s = '') => lines.push(s);

  out('// Generated by scripts/tamber-from-tokens.ts from docs/design/themes/tokens.json.');
  out('// Edit tokens.json and run `bun scripts/tamber-from-tokens.ts`, never this file.');
  out('tamber berean');
  out();
  out('axes');
  out(`  theme = ${ids.join(' | ')}`);
  out(`  accent = ${SLOTS.join(' | ')}`);
  out();
  out('theme');

  const theme = (id: string) => tokens.themes[id];
  const slot = (id: string, n: number) => {
    const s = theme(id).accents.slots.find((x) => x.slot === n);
    if (!s) throw new Error(`${id}: no accent slot ${n}`);
    return s;
  };

  for (const role of tokens.roles) {
    const name = tokenName(role);
    if (ACCENT_ROLES.has(role)) {
      const field = role === 'onAccent' ? 'onAccent' : 'hex';
      const value = (id: string, n: number) => {
        const m = slot(id, n).modes;
        return pair(hex(m.light[field], `${id}.${n}.light`), hex(m.dark[field], `${id}.${n}.dark`));
      };
      out(`  ${name} = ${value(first, 1)}`);
      ids.forEach((id) =>
        SLOTS.forEach((axis, i) => {
          if (id === first && i === 0) return;
          out(`    when theme=${id} accent=${axis}: ${value(id, i + 1)}`);
        }),
      );
      continue;
    }
    const value = (id: string) => {
      const m = theme(id).modes;
      return pair(hex(m.light[role], `${id}.light.${role}`), hex(m.dark[role], `${id}.dark.${role}`));
    };
    out(`  ${name} = ${value(first)}`);
    for (const id of others) out(`    when theme=${id}: ${value(id)}`);
  }

  const families = [...tokens.highlightFamilies].sort((a, b) => a.order - b.order);
  for (const { key } of families) {
    const value = (id: string) => {
      const m = theme(id).modes;
      const find = (mode: Mode) => mode.highlights.find((h) => h.key === key)?.hex;
      return pair(hex(find(m.light), `${id}.light.${key}`), hex(find(m.dark), `${id}.dark.${key}`));
    };
    out(`  highlight.${key} = ${value(first)}`);
    for (const id of others) out(`    when theme=${id}: ${value(id)}`);
  }
  out();
  out('// Tab icons Apple draws from SF Symbols and the other hosts from assets/icons.');
  out('icons');
  out('  icon.notes = icon(sf "note.text", svg "icons/notes.svg")');
  out('  icon.library = icon(sf "books.vertical", svg "icons/library.svg")');
  return lines.join('\n') + '\n';
}

/** app.contract's block of names: the themes, and each theme's six accents for the picker. */
export function names(tokens: Tokens): string {
  const choice = (id: string, name: string) => `Choice(id="${id}", name="${name}")`;
  const accents = (id: string) =>
    '[' + tokens.themes[id].accents.slots.map((s) => choice(SLOTS[s.slot - 1], s.name)).join(', ') + ']';
  const ids = Object.keys(tokens.themes);
  const branches = ids.slice(1).map((id) => `theme == "${id}" ? ${accents(id)} : `).join('');
  return [
    BEGIN,
    'shape Choice',
    '  id: string',
    '  name: string',
    '',
    `fn themeChoices(): Choice[] = [${ids.map((id) => choice(id, tokens.themes[id].name)).join(', ')}]`,
    `fn accentChoices(theme: string): Choice[] = ${branches}${accents(ids[0])}`,
    END,
  ].join('\n');
}

/** app.contract with its names block replaced. */
export function withNames(contract: string, tokens: Tokens): string {
  const start = contract.indexOf(BEGIN);
  const end = contract.indexOf(END);
  if (start < 0 || end < start) throw new Error(`app.contract has no "${BEGIN}" … "${END}" block`);
  return contract.slice(0, start) + names(tokens) + contract.slice(end + END.length);
}

if (import.meta.main) {
  const tokens = JSON.parse(readFileSync(TOKENS, 'utf8')) as Tokens;
  const files: [string, string][] = [
    [OUT, render(tokens)],
    [CONTRACT, withNames(readFileSync(CONTRACT, 'utf8'), tokens)],
  ];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([path, text]) => readFileSync(path, 'utf8') !== text);
    for (const [path] of stale) console.error(`${path} has drifted from tokens.json`);
    if (stale.length) {
      console.error('run `bun scripts/tamber-from-tokens.ts` in apps/berean');
      process.exit(1);
    }
    console.log('app.tamber and app.contract match tokens.json');
  } else {
    for (const [path, text] of files) writeFileSync(path, text);
    console.log('wrote app.tamber and the names in app.contract');
  }
}
